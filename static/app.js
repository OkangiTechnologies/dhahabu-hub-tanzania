function addChatMessage(text, type) {
  const messages = document.getElementById("chatMessages");
  const bubble = document.createElement("div");
  bubble.className = `chat-bubble ${type}`;
  bubble.textContent = text;
  messages.appendChild(bubble);
  messages.scrollTop = messages.scrollHeight;
}

function getAssistantAnswer(question) {
  const text = question.toLowerCase();
  if (/licen|pml|permit.*mine|start.*mine/.test(text)) return assistantAnswers.licence;
  if (/price|bei|cost|gram|value|thamani/.test(text)) return assistantAnswers.price;
  if (/sell|buy|trade|uza|nunua|buyer/.test(text)) return assistantAnswers.sell;
  if (/export|ship|send.*gold|usafirish/.test(text)) return assistantAnswers.export;
  if (/plant|process|leach|elution|ore|mtambo|usindikaji/.test(text)) return assistantAnswers.plant;
  if (/market|centre|center|soko|geita|mbeya|songwe|tabora|kigoma/.test(text)) return assistantAnswers.market;
  if (/safe|safety|chemical|mercury|cyanide|usalama|kemikali/.test(text)) return assistantAnswers.safety;
  return assistantAnswers.fallback;
}

function askSuggested(question) {
  const input = document.getElementById("chatInput");
  input.value = question;
  document.getElementById("chatForm").requestSubmit();
}

function handleChatSubmit(event) {
  event.preventDefault();
  const input = document.getElementById("chatInput");
  const question = input.value.trim();
  if (!question) return;
  addChatMessage(question, "user");
  addChatMessage(getAssistantAnswer(question), "bot");
  input.value = "";
}

async function loadPrice(){
  setText("fetchStatus","Refreshing official source…");
  try{
    const res = await fetch("/api/gold-price", {cache:"no-store"});
    const data = await res.json();
    prices = {buying:data.buying_tzs_g, market:data.market_tzs_g, worldTzs:data.world_tzs_g};
    setText("buying", money(data.buying_tzs_g));
    setText("market", money(data.market_tzs_g));
    setText("worldTzs", money(data.world_tzs_g));
    setText("worldUsd", "USD " + Number(data.world_usd_oz).toLocaleString("en-US",{maximumFractionDigits:2}));
    setText("heroPrice", money(data.buying_tzs_g) + " / g");
    setText("heroBuying", money(data.buying_tzs_g));
    setText("heroMarket", money(data.market_tzs_g));
    setText("priceDate", data.date);
    setText("heroDate", "Mining Commission • " + data.date);
    setText("fetchStatus", data.live ? "Live check successful" : "Using last verified fallback");
    const statusDot = document.getElementById("statusDot");
    if (statusDot) statusDot.style.background = data.live ? "#5dc58a" : "#c89a3c";
    calculate();
  }catch(e){
    setText("fetchStatus","Could not reach source — showing last verified value.");
  }
}

function calculate(){
  const weight = Math.max(0, Number(document.getElementById("weight").value || 0));
  const type = document.getElementById("priceType").value;
  setText("estimate", money(weight * prices[type]));
}
function toggleMenu(){document.getElementById("nav").classList.toggle("open")}

function applyTheme(theme) {
  const dark = theme === "dark";
  document.documentElement.classList.toggle("dark-mode", dark);
  const toggle = document.getElementById("themeToggle");
  if (toggle) {
    toggle.textContent = dark ? "Light" : "Dark";
    toggle.setAttribute("aria-label", dark ? "Switch to light mode" : "Switch to dark mode");
  }
  localStorage.setItem("dhahabuTheme", dark ? "dark" : "light");
}

const weightInput = document.getElementById("weight");
const priceType = document.getElementById("priceType");
const languageSelect = document.getElementById("languageSelect");
const chatForm = document.getElementById("chatForm");
if (weightInput) weightInput.addEventListener("input", calculate);
if (priceType) priceType.addEventListener("change", calculate);
if (languageSelect) languageSelect.addEventListener("change", (event) => applyLanguage(event.target.value));
if (chatForm) chatForm.addEventListener("submit", handleChatSubmit);
const themeToggle = document.getElementById("themeToggle");
if (themeToggle) themeToggle.addEventListener("click", () => applyTheme(document.documentElement.classList.contains("dark-mode") ? "light" : "dark"));

const savedLanguage = localStorage.getItem("dhahabuLanguage") || "en";
if (languageSelect) applyLanguage(savedLanguage);
applyTheme(localStorage.getItem("dhahabuTheme") || "light");
loadPrice();
