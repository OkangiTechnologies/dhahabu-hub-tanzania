const money = n => "TZS " + Number(n).toLocaleString("en-TZ", {maximumFractionDigits:2});

function setText(id, value){ const el=document.getElementById(id); if(el) el.textContent=value; }

function applyLanguage(lang = "en") {
  const selected = translations[lang] || translations.en;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (selected[key]) {
      el.textContent = selected[key];
    }
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (selected[key]) el.placeholder = selected[key];
  });
  const selector = document.getElementById("languageSelect");
  if (selector) selector.value = lang;
  localStorage.setItem("dhahabuLanguage", lang);
}

